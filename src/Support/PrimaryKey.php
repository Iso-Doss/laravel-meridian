<?php

namespace IsoDoss\Meridian\Support;

use Illuminate\Database\Schema\Blueprint;
use Illuminate\Support\Facades\Schema;
use Illuminate\Support\Str;
use Throwable;

/**
 * The primary key of Meridian's tables: a UUID (default), a ULID or an
 * auto-incrementing integer ("meridian.primary_key").
 *
 * The migrations create the column of the configured type. When writing,
 * the type of the existing column wins, so the tables created before the
 * option (integers) keep working whatever the configuration says.
 */
class PrimaryKey
{
    public const UUID = 'uuid';

    public const ULID = 'ulid';

    public const INCREMENTING = 'id';

    public const TYPES = [self::UUID, self::ULID, self::INCREMENTING];

    /**
     * Key generated by Meridian per table: "uuid", "ulid" or null (by the database).
     *
     * @var array<string, string|null>
     */
    protected static array $tables = [];

    /**
     * The configured type, "uuid" when the value is unknown.
     */
    public static function type(): string
    {
        $type = strtolower((string) config('meridian.primary_key', self::UUID));

        return in_array($type, self::TYPES, true) ? $type : self::UUID;
    }

    /**
     * Add the primary key column to a table being created.
     */
    public static function define(Blueprint $table, string $column = 'id'): void
    {
        match (static::type()) {
            self::INCREMENTING => $table->id($column),
            self::ULID => $table->ulid($column)->primary(),
            default => $table->uuid($column)->primary(),
        };
    }

    /**
     * The key Meridian generates for the rows of a table: "uuid", "ulid",
     * or null when the database increments it.
     */
    public static function of(string $table): ?string
    {
        if (array_key_exists($table, static::$tables)) {
            return static::$tables[$table];
        }

        try {
            $column = collect(Schema::connection(config('meridian.database'))->getColumns($table))
                ->first(fn (array $column) => strtolower($column['name']) === 'id');
        } catch (Throwable) {
            $column = null;
        }

        // Unknown (table not created yet): the configuration, not remembered.
        if ($column === null) {
            return static::type() === self::INCREMENTING ? null : static::type();
        }

        $name = strtolower((string) $column['type_name']);
        $full = strtolower((string) $column['type']);

        return static::$tables[$table] = match (true) {
            str_contains($name, 'int') || str_contains($name, 'serial') => null,
            str_contains($full, '(26)') => self::ULID,
            $name === 'uuid' || str_contains($full, '(36)') => self::UUID,
            // SQLite stores both as varchar: trust the configuration.
            default => static::type() === self::ULID ? self::ULID : self::UUID,
        };
    }

    /**
     * Whether Meridian generates the keys of the table.
     */
    public static function generated(string $table): bool
    {
        return static::of($table) !== null;
    }

    /**
     * A new key for a row of the table, null when the database increments it.
     * UUIDv7 and ULIDs grow with time, so sorting by id keeps the insertion order.
     */
    public static function generate(string $table): ?string
    {
        return match (static::of($table)) {
            self::UUID => (string) Str::uuid7(),
            self::ULID => strtolower((string) Str::ulid()),
            default => null,
        };
    }

    /**
     * The row with its key, when Meridian generates it.
     *
     * @param  array<string, mixed>  $row
     * @return array<string, mixed>
     */
    public static function fill(string $table, array $row): array
    {
        if (! isset($row['id']) && ($id = static::generate($table)) !== null) {
            return ['id' => $id] + $row;
        }

        return $row;
    }

    /**
     * The rows with their keys, when Meridian generates them.
     *
     * @param  array<int, array<string, mixed>>  $rows
     * @return array<int, array<string, mixed>>
     */
    public static function fillMany(string $table, array $rows): array
    {
        return array_map(fn (array $row) => static::fill($table, $row), $rows);
    }

    /**
     * Whether the value can be a key of the table (PostgreSQL rejects a
     * malformed UUID instead of finding nothing).
     */
    public static function valid(string $table, mixed $value): bool
    {
        return match (static::of($table)) {
            self::UUID => is_string($value) && Str::isUuid($value),
            self::ULID => is_string($value) && Str::isUlid($value),
            default => is_int($value) || (is_string($value) && ctype_digit($value)),
        };
    }

    /**
     * A key read from the database: an integer for the incrementing keys
     * (some drivers return them as strings), else the string.
     */
    public static function cast(mixed $value): int|string
    {
        return is_int($value) || (is_string($value) && ctype_digit($value)) ? (int) $value : (string) $value;
    }

    public static function flush(): void
    {
        static::$tables = [];
    }
}
